-- Neon (Postgres) mirror of the local brain, queried from claude.ai through the Neon MCP
-- connector as the read-only role brain_reader. Idempotent: every sync applies it when the
-- database's recorded version is lower than this one (never lower: see sync.ensure_schema).
-- Bump schema_version on every change, and keep changes additive — machines still running an
-- older ClaudeBrain keep pushing with the columns they know.
-- schema_version: 2

CREATE EXTENSION IF NOT EXISTS unaccent;

-- Bookkeeping for sync.py: schema_version, reader_password, synced:<host>. Not granted to
-- brain_reader.
CREATE TABLE IF NOT EXISTS brain_meta (
    key        text PRIMARY KEY,
    value      text NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now()
);

-- unaccent() is only STABLE; generated columns and indexes need an IMMUTABLE wrapper.
CREATE OR REPLACE FUNCTION brain_unaccent(text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$;

-- Postgres' parser keeps paths, URLs, hosts and hyphenated words as single tokens, so
-- '/home/me/paper_downloader/' would never match 'downloader'. Splitting on those separators
-- makes it tokenize like the local FTS5 index (unicode61), for documents and queries alike.
CREATE OR REPLACE FUNCTION brain_plain(text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT
AS $$ SELECT regexp_replace(brain_unaccent(lower($1)), '[/\\.:@#?=&+~-]+', ' ', 'g') $$;

CREATE TABLE IF NOT EXISTS sessions (
    session_id  text PRIMARY KEY,
    project     text,
    project_cwd text,
    entrypoint  text,
    git_branch  text,
    title       text,
    first_ts    text,
    last_ts     text,
    msg_count   integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS sessions_project ON sessions (project, last_ts);
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS repo text;  -- normalized git remote
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS host text;  -- machine the session lives on (resume there)

CREATE TABLE IF NOT EXISTS messages (
    uuid         text PRIMARY KEY,
    session_id   text NOT NULL,
    ts           text,
    role         text NOT NULL,
    entrypoint   text,
    cwd          text,
    is_sidechain integer NOT NULL DEFAULT 0,
    text         text NOT NULL,
    -- 'simple' + unaccent mirrors the local FTS5 tokenizer: no stemming, accent-insensitive.
    tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple', brain_plain(text))) STORED
);
-- Upgrade from ≤0.7.0, whose index didn't split paths/URLs: rebuild the derived column.
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_attrdef d JOIN pg_attribute a ON a.attrelid = d.adrelid AND a.attnum = d.adnum
                   WHERE d.adrelid = 'messages'::regclass AND a.attname = 'tsv'
                     AND pg_get_expr(d.adbin, d.adrelid) LIKE '%brain_plain%') THEN
        ALTER TABLE messages DROP COLUMN tsv;
        ALTER TABLE messages ADD COLUMN tsv tsvector
            GENERATED ALWAYS AS (to_tsvector('simple', brain_plain(text))) STORED;
    END IF;
END $$;
CREATE INDEX IF NOT EXISTS messages_session ON messages (session_id, ts);
CREATE INDEX IF NOT EXISTS messages_tsv ON messages USING gin (tsv);

CREATE TABLE IF NOT EXISTS digests (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- "<hostname>:<local id>": local ids restart at 1 on every machine, so they can't be the key.
    origin          text UNIQUE,
    scope           text NOT NULL,
    key             text NOT NULL,
    covers_until_ts text,
    content         text NOT NULL,
    created_at      text NOT NULL
);
-- Upgrade from 0.2.x, where id was the local SQLite id.
ALTER TABLE digests ADD COLUMN IF NOT EXISTS origin text;
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_attribute
                   WHERE attrelid = 'digests'::regclass AND attname = 'id' AND attidentity <> '') THEN
        ALTER TABLE digests ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_constraint WHERE conname = 'digests_origin_key') THEN
        ALTER TABLE digests ADD CONSTRAINT digests_origin_key UNIQUE (origin);
    END IF;
END $$;

-- Sessions forgotten on any machine (`claude-brain forget`): every sync deletes them from here
-- and pulls the list, so each machine drops them from its own archive too. (v2)
CREATE TABLE IF NOT EXISTS forgotten (
    session_id   text PRIMARY KEY,
    forgotten_at text NOT NULL
);

-- Folder-name aliases shared by all machines (last write wins, merged by sync.py).
CREATE TABLE IF NOT EXISTS aliases (
    folder     text PRIMARY KEY,
    project    text NOT NULL,
    updated_at text NOT NULL
);

-- Query API for claude.ai: `SELECT * FROM brain_xxx(...)`. Project names match partially.

-- Search syntax shared with the local CLI (brain/query.py::fts_query): words are ANDed and
-- match their variants (light stem + prefix), `a OR b`, "exact phrase", -exclude.
-- Keep STEM_SUFFIXES / STEM_MIN / PREFIX_MIN identical to brain/query.py.
CREATE OR REPLACE FUNCTION brain_stem(w text) RETURNS text
LANGUAGE plpgsql IMMUTABLE STRICT AS $$
DECLARE suffix text;
BEGIN
    FOREACH suffix IN ARRAY ARRAY['aciones', 'imientos', 'amientos', 'iciones', 'iones', 'acion', 'icion', 'mente', 'ando', 'iendo', 'ados', 'adas', 'idos', 'idas', 'ings', 'ado', 'ada', 'ido', 'ida', 'ion', 'ing', 'es', 'ar', 'er', 'ir', 'ed', 's', 'a', 'e', 'o'] LOOP
        IF right(w, length(suffix)) = suffix AND length(w) - length(suffix) >= 4 THEN
            RETURN left(w, length(w) - length(suffix));
        END IF;
    END LOOP;
    RETURN w;
END $$;

CREATE OR REPLACE FUNCTION brain_tsquery(q text) RETURNS tsquery
LANGUAGE plpgsql STABLE AS $$
DECLARE
    token text; negate boolean; phrase boolean; join_next boolean := false;
    parts text[]; kinds int[]; n int; term text;
    groups text[] := '{}'; excluded text[] := '{}'; expr text;
BEGIN
    FOR token IN SELECT m[1] FROM regexp_matches(coalesce(q, ''), '("[^"]*"|\S+)', 'g') AS m LOOP
        IF token = 'OR' THEN
            join_next := cardinality(groups) > 0;
            CONTINUE;
        END IF;
        negate := left(token, 1) = '-' AND length(token) > 1;
        IF negate THEN token := substr(token, 2); END IF;
        phrase := length(token) >= 2 AND left(token, 1) = '"' AND right(token, 1) = '"';
        IF phrase THEN token := substr(token, 2, length(token) - 2); END IF;
        -- Tokenize like to_tsvector does; drop blanks (12) and hyphenated-word parts (9-11),
        -- whose whole compound is indexed too.
        SELECT array_agg(t.token ORDER BY t.ord), array_agg(t.tokid ORDER BY t.ord)
          INTO parts, kinds
          FROM ts_parse('default', brain_plain(token)) WITH ORDINALITY AS t(tokid, token, ord)
         WHERE t.tokid NOT IN (9, 10, 11, 12);
        IF parts IS NULL THEN CONTINUE; END IF;
        n := cardinality(parts);
        IF NOT phrase AND kinds[n] IN (1, 2) THEN parts[n] := brain_stem(parts[n]); END IF;
        SELECT string_agg(quote_literal(x), ' <-> ' ORDER BY i) INTO term
          FROM unnest(parts) WITH ORDINALITY AS u(x, i);
        IF NOT phrase AND length(parts[n]) >= 3 THEN term := term || ':*'; END IF;
        IF negate THEN
            excluded := excluded || term;
        ELSIF join_next THEN
            groups[cardinality(groups)] := groups[cardinality(groups)] || ' | ' || term;
        ELSE
            groups := groups || term;
        END IF;
        join_next := false;
    END LOOP;
    IF cardinality(groups) = 0 THEN RETURN NULL; END IF;
    SELECT string_agg('(' || g || ')', ' & ') INTO expr FROM unnest(groups) AS g;
    IF cardinality(excluded) > 0 THEN
        SELECT expr || string_agg(' & !(' || x || ')', '') INTO expr FROM unnest(excluded) AS x;
    END IF;
    RETURN expr::tsquery;
END $$;

CREATE OR REPLACE FUNCTION brain_projects()
RETURNS TABLE (project text, sessions bigint, messages bigint, last_ts text, folders text)
LANGUAGE sql STABLE AS $$
    SELECT project, count(*), sum(msg_count), max(last_ts),
           string_agg(DISTINCT project_cwd, ' | ')
    FROM sessions WHERE msg_count > 0 AND project IS NOT NULL
    GROUP BY project ORDER BY max(last_ts) DESC
$$;

DROP FUNCTION IF EXISTS brain_recent(text, integer);
CREATE OR REPLACE FUNCTION brain_recent(p_project text DEFAULT NULL, p_limit integer DEFAULT 10)
RETURNS TABLE (session_id text, project text, entrypoint text, title text,
               first_ts text, last_ts text, msg_count integer, host text)
LANGUAGE sql STABLE AS $$
    SELECT session_id, project, entrypoint, title, first_ts, last_ts, msg_count, host
    FROM sessions
    WHERE msg_count > 0 AND (p_project IS NULL OR project ILIKE '%' || p_project || '%')
    ORDER BY last_ts DESC LIMIT p_limit
$$;

DROP FUNCTION IF EXISTS brain_search(text, text, text, integer);
CREATE OR REPLACE FUNCTION brain_search(q text, p_project text DEFAULT NULL,
                                        p_since text DEFAULT NULL, p_limit integer DEFAULT 20)
RETURNS TABLE (ts text, project text, entrypoint text, session_id text, title text,
               role text, snippet text, host text)
LANGUAGE sql STABLE AS $$
    WITH query AS (SELECT brain_tsquery(q) AS tq)
    SELECT m.ts, s.project, m.entrypoint, m.session_id, s.title, m.role,
           ts_headline('simple', brain_unaccent(m.text), query.tq,
                       'StartSel=[, StopSel=], MaxWords=35, MinWords=12, MaxFragments=2'),
           s.host
    FROM messages m JOIN sessions s USING (session_id), query
    WHERE m.tsv @@ query.tq
      AND m.role IN ('user', 'assistant', 'summary') AND m.is_sidechain = 0
      AND (p_project IS NULL OR s.project ILIKE '%' || p_project || '%')
      AND (p_since IS NULL OR m.ts >= p_since)
    ORDER BY ts_rank(m.tsv, query.tq) DESC LIMIT p_limit
$$;

DROP FUNCTION IF EXISTS brain_project(text);
CREATE OR REPLACE FUNCTION brain_project(p_name text)
RETURNS TABLE (session_id text, project text, entrypoint text, title text,
               first_ts text, last_ts text, msg_count integer, host text)
LANGUAGE sql STABLE AS $$
    SELECT session_id, project, entrypoint, title, first_ts, last_ts, msg_count, host
    FROM sessions
    WHERE msg_count > 0 AND project ILIKE '%' || p_name || '%'
    ORDER BY first_ts
$$;

CREATE OR REPLACE FUNCTION brain_digest(p_key text)
RETURNS TABLE (scope text, key text, covers_until_ts text, created_at text, content text)
LANGUAGE sql STABLE AS $$
    SELECT DISTINCT ON (scope, key) scope, key, covers_until_ts, created_at, content
    FROM digests WHERE key ILIKE '%' || p_key || '%'
    ORDER BY scope, key, created_at DESC
$$;

CREATE OR REPLACE FUNCTION brain_session(p_session text, p_after text DEFAULT NULL,
                                         p_limit integer DEFAULT 200)
RETURNS TABLE (ts text, role text, text text)
LANGUAGE sql STABLE AS $$
    SELECT m.ts, m.role, m.text FROM messages m
    WHERE m.session_id LIKE p_session || '%'
      AND m.role IN ('user', 'assistant', 'summary') AND m.is_sidechain = 0
      AND (p_after IS NULL OR m.ts > p_after)
    ORDER BY m.ts LIMIT p_limit
$$;

-- Read-only role for the MCP connector (?roleName=brain_reader). Created here with SQL on
-- purpose: Console-created roles join neon_superuser and can read everything.
-- The MCP logs in as this role, so it needs a password, set once by `claude-brain cloud setup`
-- (sync.set_reader_password); without one the connector fails with "missing authentication
-- credentials".
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'brain_reader') THEN
        CREATE ROLE brain_reader LOGIN;
    END IF;
END $$;
GRANT USAGE ON SCHEMA public TO brain_reader;
GRANT SELECT ON sessions, messages, digests, aliases TO brain_reader;
-- Lets the owner connection switch to brain_reader (SET ROLE) without inheriting anything.
GRANT brain_reader TO CURRENT_USER WITH INHERIT FALSE, SET TRUE;
